        out << "\nRisultati: " << g.resultsName << " (" << g.results.format << ", " << g.results.steps.size() << " passi, "
            << g.results.fields.size() << " campi)" << g.resultsNote;
    if (!g.viewNote.empty()) out << "\n" << g.viewNote;
