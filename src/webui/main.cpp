/** Splits `text` at `separator`, dropping empty items. */
std::vector<std::string> splitText(const std::string& text, char separator) {
    std::vector<std::string> out;
    std::istringstream in(text);
    std::string item;
    while (std::getline(in, item, separator)) if (!item.empty()) out.push_back(item);
    return out;
}

bool parseId(const std::string& text, std::uint64_t& value) {
    if (text.empty() || text.size() > 19 || text.find_first_not_of("0123456789") != std::string::npos) return false;
    value = std::stoull(text);
    return true;
}

/**
 * Selection as sent by the page: mode, then a payload of ids. Nodes and elements: "1,2,3". Faces: "element:n1,n2,n3;element:n1,n2,n3".
 */
bool parseSelection(const std::string& mode, const std::string& payload, OpenModel::ViewerSelection& out, std::string& error) {
    out = OpenModel::ViewerSelection{};
    out.mode = mode;
    if (mode == "node" || mode == "element") {
        for (const auto& item : splitText(payload, ',')) {
            std::uint64_t id;
            if (!parseId(item, id)) { error = "Selezione non valida: '" + item + "'"; return false; }
            (mode == "node" ? out.nodes : out.elements).push_back(id);
        }
    } else if (mode == "face") {
        for (const auto& item : splitText(payload, ';')) {
            const auto colon = item.find(':');
            const auto ids = colon == std::string::npos ? std::vector<std::string>{} : splitText(item.substr(colon + 1), ',');
            OpenModel::PickedFace face;
            if (colon == std::string::npos || ids.size() != 3 || !parseId(item.substr(0, colon), face.element)) { error = "Selezione di facce non valida: '" + item + "'"; return false; }
            for (std::size_t k = 0; k < 3; ++k) if (!parseId(ids[k], face.nodes[k])) { error = "Selezione di facce non valida: '" + item + "'"; return false; }
            out.faces.push_back(face);
        }
    } else {
        error = "Niente è selezionato: attiva la selezione nel pannello e scegli nodi, elementi o facce.";
        return false;
    }
    return true;
}

std::string selectionPayload(const OpenModel::ViewerSelection& s) {
    std::string out;
    auto append = [&](const std::string& item, char sep) { if (!out.empty()) out += sep; out += item; };
    for (const auto n : s.nodes) append(std::to_string(n), ',');
    for (const auto e : s.elements) append(std::to_string(e), ',');
    for (const auto& f : s.faces)
        append(std::to_string(f.element) + ":" + std::to_string(f.nodes[0]) + "," + std::to_string(f.nodes[1]) + "," + std::to_string(f.nodes[2]), ';');
    return out;
}

const char* kindItalian(OpenModel::GroupKind kind) {
    return kind == OpenModel::GroupKind::NodeSet ? "nodi" : kind == OpenModel::GroupKind::ElementGroup ? "elementi" : "facce";
}

