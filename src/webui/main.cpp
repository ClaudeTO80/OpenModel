/** Forgets the solver results: they are tied to the node numbering of the mesh they were loaded for. */
void clearResults() {
    g.results.clear();
    g.resultsName.clear();
    g.resultsStep = OpenModel::BindOptions::kLastStep;
    g.resultsNote.clear();
}

/** Appends the warnings of a binding to a message, one per line. */
std::string diagnosticsText(const std::vector<OpenModel::ImportDiagnostic>& diagnostics) {
    std::string text;
    for (const auto& d : diagnostics) text += "\n" + d.code + ": " + d.message;
    return text;
}

/**
 * Attaches the loaded results (if any) to the view options of the current mesh.
 * On failure the view stays plain and the reason is stored in g.resultsNote.
 */
OpenModel::BindResult attachResults(const MeshData& mesh, WebViewOptions& options) {
    OpenModel::BindResult bound;
    g.resultsNote.clear();
    if (g.results.empty()) return bound;
    OpenModel::BindOptions bind;
    bind.step = g.resultsStep;
    bind.sourceName = g.resultsName;
    bound = OpenModel::bindResults(mesh, g.results, bind, options);
    if (!bound.success) g.resultsNote = "Results not applied: " + bound.error;
    else g.resultsNote = diagnosticsText(bound.diagnostics);
    return bound;
}

/** Resolves a user supplied path to an absolute one. */
fs::path absolutePath(const std::string& text) {
    std::error_code ec;
    auto path = fs::absolute(fs::path(text), ec);
    return ec ? fs::path(text) : path;
}

/** Sidecar identity: face indices are only meaningful for the exact imported source file. */
bool cadSourceFingerprint(const fs::path& source, std::uintmax_t& size, long long& modified) {
    std::error_code ec;
    size = fs::file_size(source, ec);
    if (ec) return false;
    const auto stamp = fs::last_write_time(source, ec);
    if (ec) return false;
    modified = static_cast<long long>(stamp.time_since_epoch().count());
    return true;
}

fs::path cadGroupsPath(const std::string& source) {
    return fs::path(source + ".omgroups");
}

bool saveCADFaceGroups(const std::string& source, const std::vector<UserCADFaceGroup>& groups, std::string& error) {
    std::uintmax_t size = 0;
    long long modified = 0;
    if (!cadSourceFingerprint(source, size, modified)) {
        error = "Cannot read the size/date of the CAD file to save the groups.";
        return false;
    }
    const auto target = cadGroupsPath(source);
    const auto temporary = fs::path(target.string() + ".tmp");
    {
        std::ofstream out(temporary, std::ios::trunc);
        if (!out) { error = "Cannot create the CAD groups sidecar: " + temporary.string(); return false; }
        out << "OPENMODEL_CAD_FACE_GROUPS 1\n" << std::quoted(source) << ' ' << size << ' ' << modified << '\n';
        out << groups.size() << '\n';
        for (const auto& group : groups) {
            out << std::quoted(group.name) << ' ' << group.faceIds.size();
            for (const int id : group.faceIds) out << ' ' << id;
            out << '\n';
        }
        if (!out) { error = "Writing the CAD groups sidecar failed."; return false; }
    }
    std::error_code ec;
    fs::rename(temporary, target, ec);
    if (ec) {
        // Windows does not replace an existing destination with rename().
        std::error_code removeError;
        fs::remove(target, removeError);
        ec.clear();
        fs::rename(temporary, target, ec);
    }
    if (ec) { error = "Cannot finalize the sidecar: " + ec.message(); return false; }
    return true;
}

bool loadCADFaceGroups(const std::string& source, const SurfaceMesh& surface,
                       std::vector<UserCADFaceGroup>& groups, std::string& note) {
    groups.clear();
    const auto path = cadGroupsPath(source);
    std::error_code ec;
    if (!fs::exists(path, ec)) return true;
    std::ifstream in(path);
    std::string magic;
    int version = 0;
    std::string storedSource;
    std::uintmax_t storedSize = 0;
    long long storedModified = 0;
    if (!(in >> magic >> version) || magic != "OPENMODEL_CAD_FACE_GROUPS" || version != 1 ||
        !(in >> std::quoted(storedSource) >> storedSize >> storedModified)) {
        note = "Invalid CAD groups sidecar: ignored.";
        return false;
    }
    std::uintmax_t actualSize = 0;
    long long actualModified = 0;
    if (!cadSourceFingerprint(source, actualSize, actualModified) ||
        storedSource != source || storedSize != actualSize || storedModified != actualModified) {
        note = "CAD groups sidecar refers to a different version of the file: ignored to avoid wrong associations.";
        return false;
    }
    std::set<int> availableFaces;
    for (const auto& part : surface.parts) if (part.sourceFaceId >= 0) availableFaces.insert(part.sourceFaceId);
    std::size_t count = 0;
    if (!(in >> count) || count > 10000) { note = "Invalid number of CAD groups: sidecar ignored."; return false; }
    std::vector<UserCADFaceGroup> loaded;
    std::set<std::string> names;
    for (std::size_t i = 0; i < count; ++i) {
        UserCADFaceGroup group;
        std::size_t faceCount = 0;
        if (!(in >> std::quoted(group.name) >> faceCount) || group.name.empty() || faceCount == 0 || faceCount > availableFaces.size() ||
            !names.insert(group.name).second) {
            note = "Invalid CAD group definition: sidecar ignored.";
            return false;
        }
        for (std::size_t j = 0; j < faceCount; ++j) {
            int id = -1;
            if (!(in >> id) || availableFaces.count(id) == 0) {
                note = "The sidecar contains a face ID that is not in the imported CAD: groups ignored.";
                return false;
            }
            group.faceIds.push_back(id);
        }
        std::sort(group.faceIds.begin(), group.faceIds.end());
        if (std::adjacent_find(group.faceIds.begin(), group.faceIds.end()) != group.faceIds.end()) {
            note = "The sidecar contains duplicate faces: groups ignored.";
            return false;
        }
        loaded.push_back(std::move(group));
    }
    groups = std::move(loaded);
    return true;
}

/** Appends extension to a base name unless it is already present. */
std::string withExtension(const std::string& base, const std::string& ext) {
    if (lowerExtension(fs::path(base)) == ext) return base;
    return base + ext;
}

