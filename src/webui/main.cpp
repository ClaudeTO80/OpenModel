MeshData makeDemoGrid(std::size_t n) {
    MeshData mesh;
    const std::size_t s = n + 1;
    auto idx = [s](std::size_t x, std::size_t y, std::size_t z) { return static_cast<NodeIndex>((z * s + y) * s + x); };
    for (std::size_t z = 0; z <= n; ++z)
        for (std::size_t y = 0; y <= n; ++y)
            for (std::size_t x = 0; x <= n; ++x)
                mesh.addNode(static_cast<NodeId>(idx(x, y, z) + 1), 2.0 * x / n, double(y) / n, double(z) / n);
    ElementId id = 1;
    std::vector<ElementId> left, right;
    for (std::size_t z = 0; z < n; ++z)
        for (std::size_t y = 0; y < n; ++y)
            for (std::size_t x = 0; x < n; ++x) {
                const NodeIndex a = idx(x, y, z), b = idx(x + 1, y, z), c = idx(x, y + 1, z), d = idx(x + 1, y + 1, z);
                const NodeIndex e = idx(x, y, z + 1), f = idx(x + 1, y, z + 1), gg = idx(x, y + 1, z + 1), h = idx(x + 1, y + 1, z + 1);
                const NodeIndex t[6][4] = {{a, b, d, h}, {a, d, c, h}, {a, c, gg, h}, {a, gg, e, h}, {a, e, f, h}, {a, f, b, h}};
                const bool isLeft = x < n / 2;
                for (const auto& q : t) {
                    mesh.addElement(isLeft ? "acciaio" : "alluminio", ElementType::Tetrahedron4, id, {q[0], q[1], q[2], q[3]});
                    (isLeft ? left : right).push_back(id++);
                }
            }
    mesh.addPhysicalGroup("acciaio", 3, 1, left, "steel");
    mesh.addPhysicalGroup("alluminio", 3, 2, right, "aluminium");
    return mesh;
}

bool tessellateCurrent(std::string& error) {
    if (!g.cad) { error = "Nessun modello CAD caricato."; return false; }
    MeshingOptions options;
    options.dimension = MeshDimension::Surface;
    options.linearDeflection = g.linearDeflection;
    options.angularDeflection = g.angularDeflection;
    SurfaceMesh output;
    SurfaceMesher mesher;
    const auto report = mesher.build(g.cad, options, output);
    if (!report.ok) { error = report.error; return false; }
    g.surface = std::move(output);
    return true;
}

bool validParameters(double linear, double angular) {
    return std::isfinite(linear) && linear > 0.0 && std::isfinite(angular) && angular > 0.0 && angular <= 3.141592653589793;
}

