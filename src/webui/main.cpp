/** Builds a complete HTTP response in a WebUI-owned buffer. */
const void* httpResponse(int status, const char* statusText, const char* contentType, const unsigned char* body, std::size_t size, int* length) {
    char header[256];
    const int headerLength = std::snprintf(header, sizeof(header),
        "HTTP/1.1 %d %s\r\nContent-Type: %s\r\nContent-Length: %zu\r\nCache-Control: no-store\r\n\r\n", status, statusText, contentType, size);
    *length = headerLength + static_cast<int>(size);
    auto* response = static_cast<unsigned char*>(webui_malloc(static_cast<std::size_t>(*length)));
    std::memcpy(response, header, static_cast<std::size_t>(headerLength));
    if (size) std::memcpy(response + headerLength, body, size);
    return response;
}

/** Serves the embedded viewer page and the current MGWV model; everything else falls through. */
const void* fileHandler(const char* filename, int* length) {
    std::string name = filename ? filename : "";
    const auto query = name.find('?');
    if (query != std::string::npos) name.resize(query);
    while (!name.empty() && name.front() == '/') name.erase(name.begin());
    if (name == "viewer.html")
        return httpResponse(200, "OK", "text/html; charset=utf-8", viewer_html, viewer_html_size, length);
    if (name == "model.mgwv") {
        std::unique_lock<std::mutex> lock(g_mutex, std::try_to_lock);
        if (!lock.owns_lock()) return httpResponse(503, "Service Unavailable", "text/plain", nullptr, 0, length);
        if (g.view.empty()) return httpResponse(404, "Not Found", "text/plain", nullptr, 0, length);
        return httpResponse(200, "OK", "application/octet-stream", g.view.data(), g.view.size(), length);
    }
    return nullptr;
}

