void listDirectory(webui_event_t* e) {
    const std::string requested = getStringArg(e, 0);
    const std::string filter = getStringArg(e, 1);
    std::set<std::string> extensions;
    {
        std::stringstream tokens(filter);
        std::string token;
        while (std::getline(tokens, token, ',')) extensions.insert(token);
    }
    std::error_code ec;
    fs::path dir = requested.empty() ? fs::current_path(ec) : absolutePath(requested);
    if (!fs::is_directory(dir, ec)) dir = dir.parent_path();
    dir = fs::weakly_canonical(dir, ec);
    if (ec || !fs::is_directory(dir, ec)) {
        webui_return_string(e, "{\"ok\":false,\"message\":\"Folder not accessible.\"}");
        return;
    }
    struct Entry { std::string name; bool dir; };
    std::vector<Entry> entries;
    for (fs::directory_iterator it(dir, fs::directory_options::skip_permission_denied, ec), end; !ec && it != end; it.increment(ec)) {
        std::error_code entryEc;
        const bool isDir = it->is_directory(entryEc);
        const std::string name = it->path().filename().string();
        if (name.empty() || name[0] == '.') continue;
        if (isDir) entries.push_back({name, true});
        else if (extensions.empty() || extensions.count(lowerExtension(it->path()))) entries.push_back({name, false});
        if (entries.size() >= 5000) break;
    }
    std::sort(entries.begin(), entries.end(), [](const Entry& a, const Entry& b) {
        if (a.dir != b.dir) return a.dir;
        return a.name < b.name;
    });
    std::ostringstream out;
    const std::string parent = dir.has_parent_path() && dir.parent_path() != dir ? dir.parent_path().string() : dir.string();
    out << "{\"ok\":true,\"message\":\"\",\"path\":\"" << jsonEscape(dir.string()) << "\",\"parent\":\"" << jsonEscape(parent)
        << "\",\"sep\":\"" << jsonEscape(std::string(1, static_cast<char>(fs::path::preferred_separator))) << "\",\"entries\":[";
    for (std::size_t i = 0; i < entries.size(); ++i) {
        if (i) out << ',';
        out << "{\"name\":\"" << jsonEscape(entries[i].name) << "\",\"dir\":" << (entries[i].dir ? "true" : "false") << '}';
    }
    out << "]}";
    webui_return_string(e, out.str().c_str());
}

